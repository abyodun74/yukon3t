/** Width and height from a WebP file's header (lossy "VP8 " or extended "VP8X"; sharp writes one of these). */
function webpSize(file: Buffer): { width: number; height: number } {
  expect(file.toString("ascii", 0, 4)).toBe("RIFF");
  expect(file.toString("ascii", 8, 12)).toBe("WEBP");
  const chunk = file.toString("ascii", 12, 16);
  if (chunk === "VP8X") {
    return { width: 1 + file.readUIntLE(24, 3), height: 1 + file.readUIntLE(27, 3) };
  }
  expect(chunk).toBe("VP8 ");
  return { width: file.readUInt16LE(26) & 0x3fff, height: file.readUInt16LE(28) & 0x3fff };
}

const publicFile = (src: string) => path.join(process.cwd(), "public", src);

describe("gift art resolution", () => {
  it("resolves the Luxury Red Rose to the owner's Legendary artwork, with both sizes in srcSet", () => {
    const image = GIFT_LEGENDARY_ART_IMAGES["luxury-red-rose"];
    expect(resolveGiftArt("luxury-red-rose")).toEqual({
      type: "image",
      ...image,
      srcSet: `${image.thumbSrc} 256w, ${image.src} 768w`,
    });
  });

  it("resolves the drawn gifts to their SVG, and anything unknown to the sparkle", () => {
    expect(resolveGiftArt("heart-burst")).toEqual({ type: "svg", key: "heart-burst" });
    expect(resolveGiftArt("thank-you")).toEqual({ type: "svg", key: "thank-you" });
    expect(resolveGiftArt("not-a-gift")).toEqual({ type: "svg", key: "sparkle" });
    expect(resolveGiftArt("toString")).toEqual({ type: "svg", key: "sparkle" });
    expect(resolveGiftArt("__proto__")).toEqual({ type: "svg", key: "sparkle" });
  });

  it("has art for every catalog item (none falls back to the sparkle), and no key is both kinds", () => {
    for (const item of GIFT_ITEMS) {
      const art = resolveGiftArt(item.assetKey);
      if (art.type === "svg") expect(art.key, item.slug).toBe(item.assetKey);
    }
    for (const key of Object.keys(GIFT_IMAGE_ASSETS)) {
      expect(GIFT_SVG_ASSET_KEYS as readonly string[]).not.toContain(key);
    }
  });

  it.each(Object.entries(GIFT_IMAGE_ASSETS))("ships web-ready files for %s, same-origin, within budget", (_key, asset) => {
    for (const src of [asset.src, asset.thumbSrc]) expect(src).toMatch(/^\/gifts\/art\/[a-z0-9-]+\.[0-9a-f]{10}\.webp$/);
    const large = readFileSync(publicFile(asset.src));
    const thumb = readFileSync(publicFile(asset.thumbSrc));
    expect(webpSize(large)).toEqual({ width: asset.width, height: asset.height });
    expect(webpSize(thumb)).toEqual({ width: asset.thumbWidth, height: asset.thumbHeight });
    expect(statSync(publicFile(asset.src)).size).toBeLessThan(120 * 1024);
    expect(statSync(publicFile(asset.thumbSrc)).size).toBeLessThan(25 * 1024);
  });
});

describe("gift icon sheet art (src/lib/gift-art-images.ts, generated by scripts/slice-gift-art.py)", () => {
  const ART_DIR = path.join(process.cwd(), "public", "gifts", "art");
  const entries = Object.entries(GIFT_ART_IMAGES);

  it("covers exactly the gifts the sheet's icon is used for (33; not its second Trophy Frame nor its Gold Orchid)", () => {
    expect(Object.keys(GIFT_ART_IMAGES).sort()).toEqual(
      [
        "aurora-frame",
        "aurora-sweep",
        "birthday-balloons",
        "birthday-candle",
        "cake-slice",
        "coffee",
        "confetti",
        "fireworks",
        "forget-me-not",
        "frost-frame",
        "gg-badge",
        "gold-ring-frame",
        "gold-star",
        "grad-cap",
        "heartbeat-note",
        "high-five",
        "houseplant",
        "keepsake-locket",
        "kindred-spirit",
        "lantern",
        "level-up",
        "midnight-crystal-frame",
        "paper-crane",
        "pixel-heart",
        "playful-kitten",
        "rose",
        "shared-table",
        "shooting-star",
        "sunset-postcard",
        "supporter-star",
        "teddy-bear",
        "trophy-frame",
        "wave",
      ].sort(),
    );
  });

  it("keys every entry by a real catalog item's assetKey, and is the only art those gifts have", () => {
    const assetKeys = new Set<string>(GIFT_ITEMS.map((i) => i.assetKey));
    for (const [key] of entries) {
      expect(assetKeys.has(key), key).toBe(true);
      expect(GIFT_SVG_ASSET_KEYS as readonly string[], key).not.toContain(key);
      expect(resolveGiftArt(key)).toMatchObject({ type: "image", src: GIFT_ART_IMAGES[key as keyof typeof GIFT_ART_IMAGES].src });
    }
  });

  it("gives every marketplace gift a picture except the one the sheet has no icon for", () => {
    const slugs = GIFT_MARKET.flatMap((m) => GIFT_PRODUCTS.find((p) => p.sku === m.sku)!.items.map((i) => i.slug));
    const withoutPicture = slugs.filter((slug) => resolveGiftArt(GIFT_ITEMS.find((i) => i.slug === slug)!.assetKey).type !== "image");
    expect(withoutPicture).toEqual(["heart-burst"]);
  });

  it.each(entries)("%s: both files exist, are square WebP of the stated size, within budget, named by their content", (_key, image) => {
    const files = [
      { src: image.src, width: image.width, height: image.height, budget: 80 * 1024 },
      { src: image.thumbSrc, width: image.thumbWidth, height: image.thumbHeight, budget: 30 * 1024 },
    ];
    for (const { src, width, height, budget } of files) {
      expect(src).toMatch(/^\/gifts\/art\/[a-z0-9-]+\.[0-9a-f]{10}\.webp$/);
      const file = readFileSync(publicFile(src));
      expect(webpSize(file)).toEqual({ width, height });
      expect(width).toBe(height);
      expect(file.length).toBeLessThan(budget);
      // The name carries the first 10 hex digits of the file's SHA-256, which is what lets it be cached as immutable.
      expect(src).toContain(`.${createHash("sha256").update(file).digest("hex").slice(0, 10)}.webp`);
    }
    expect(image.thumbWidth).toBeLessThan(image.width);
  });

  it("ships no file the three manifests don't name, and no file twice (total under 3 MB)", () => {
    const named = [...entries, ...Object.entries(GIFT_LEGENDARY_ART_IMAGES), ...Object.entries(GIFT_JEWELRY_ART_IMAGES)].flatMap(([, image]) =>
      [image.src, image.thumbSrc].map((src) => path.basename(src)),
    );
    expect(new Set(named).size).toBe(named.length);
    const onDisk = readdirSync(ART_DIR);
    expect([...onDisk].sort()).toEqual([...named].sort());
    const total = onDisk.reduce((sum, file) => sum + statSync(path.join(ART_DIR, file)).size, 0);
    expect(total).toBeLessThan(3 * 1024 * 1024);
  });
});

describe("Legendary artwork (src/lib/gift-legendary-art-images.ts, scripts/slice-gift-art.py --legendary)", () => {
  const entries = Object.entries(GIFT_LEGENDARY_ART_IMAGES);

  it("is the Luxury Red Rose's and the Gold Orchid's art, and replaces any icon they had", () => {
    expect(Object.keys(GIFT_LEGENDARY_ART_IMAGES).sort()).toEqual(["gold-orchid", "luxury-red-rose"]);
    const assetKeys = new Set<string>(GIFT_ITEMS.map((i) => i.assetKey));
    for (const [key, image] of entries) {
      expect(assetKeys.has(key), key).toBe(true);
      expect(Object.keys(GIFT_ART_IMAGES), key).not.toContain(key);
      expect(GIFT_SVG_ASSET_KEYS as readonly string[], key).not.toContain(key);
      expect(GIFT_IMAGE_ASSETS[key]).toEqual(image);
    }
  });

  it.each(entries)("%s: 768 px + 256 px square WebP with an alpha fade, within budget, named by their content", (_key, image) => {
    expect([image.width, image.height, image.thumbWidth, image.thumbHeight]).toEqual([768, 768, 256, 256]);
    const files = [
      { src: image.src, size: 768, budget: 120 * 1024 },
      { src: image.thumbSrc, size: 256, budget: 25 * 1024 },
    ];
    for (const { src, size, budget } of files) {
      expect(src).toMatch(/^\/gifts\/art\/[a-z0-9-]+\.[0-9a-f]{10}\.webp$/);
      const file = readFileSync(publicFile(src));
      expect(webpSize(file)).toEqual({ width: size, height: size });
      // VP8X with the alpha flag: the soft edge that blends the art on the dark stage.
      expect(file.toString("ascii", 12, 16)).toBe("VP8X");
      expect(file[20] & 0x10).toBe(0x10);
      expect(file.length).toBeLessThan(budget);
      expect(src).toContain(`.${createHash("sha256").update(file).digest("hex").slice(0, 10)}.webp`);
    }
  });

  it("the Diamond Jewelry Gift Box (scripts/slice-gift-art.py --jewelry) is its own manifest: one key, same sizes and budget, alpha fade", () => {
    expect(Object.keys(GIFT_JEWELRY_ART_IMAGES)).toEqual(["diamond-jewelry-box"]);
    const image = GIFT_JEWELRY_ART_IMAGES["diamond-jewelry-box"];
    expect(GIFT_IMAGE_ASSETS["diamond-jewelry-box"]).toEqual(image);
    expect(Object.keys(GIFT_ART_IMAGES)).not.toContain("diamond-jewelry-box");
    expect(Object.keys(GIFT_LEGENDARY_ART_IMAGES)).not.toContain("diamond-jewelry-box");
    expect(GIFT_ITEMS.some((i) => i.assetKey === "diamond-jewelry-box")).toBe(true);
    // Kept whole at its own aspect (1402 x 1122 source): 768 x 615 and 256 x 205, never cropped or padded.
    expect([image.width, image.height, image.thumbWidth, image.thumbHeight]).toEqual([768, 615, 256, 205]);
    for (const { src, width, height, budget } of [
      { src: image.src, width: 768, height: 615, budget: 120 * 1024 },
      { src: image.thumbSrc, width: 256, height: 205, budget: 25 * 1024 },
    ]) {
      const file = readFileSync(publicFile(src));
      expect(webpSize(file)).toEqual({ width, height });
      expect(file.toString("ascii", 12, 16)).toBe("VP8X");
      expect(file[20] & 0x10).toBe(0x10);
      expect(file.length).toBeLessThan(budget);
      expect(src).toContain(`.${createHash("sha256").update(file).digest("hex").slice(0, 10)}.webp`);
    }
  });

  it("the old photo files of the rose are gone", () => {
    expect(readdirSync(path.join(process.cwd(), "public", "gifts")).filter((f) => f.endsWith(".webp"))).toEqual([]);
  });
});

describe("GiftArt", () => {
  it("renders the Legendary artwork as a bare, lazy, sized <img> with the localized name as alt text", () => {
    const html = renderToStaticMarkup(createElement(GiftArt, { assetKey: "luxury-red-rose", name: "Rosa roja de lujo", size: 44 }));
    const image = GIFT_LEGENDARY_ART_IMAGES["luxury-red-rose"];
    expect(html).toMatch(/^<img /);
    expect(html).toContain('alt="Rosa roja de lujo"');
    expect(html).toContain('loading="lazy"');
    expect(html).toContain('width="44"');
    expect(html).toContain('height="44"');
    expect(html).toContain('sizes="44px"');
    expect(html).toContain(`src="${image.thumbSrc}"`);
    expect(html).toContain("object-contain");
    expect(html).not.toContain("rounded-[22%]");
    expect(html).not.toContain("<svg");
  });

  it("loads eagerly when asked (art on screen as soon as it mounts, e.g. the open-gift overlay)", () => {
    const html = renderToStaticMarkup(createElement(GiftArt, { assetKey: "luxury-red-rose", name: "x", size: 160, eager: true }));
    expect(html).toContain('loading="eager"');
  });

  it("renders a sheet icon as a bare, lazy, sized <img> (no card), drawn whole, named by its alt text", () => {
    const html = renderToStaticMarkup(createElement(GiftArt, { assetKey: "rose", name: "Rosa", size: 44 }));
    const image = GIFT_ART_IMAGES.rose;
    expect(html).toMatch(/^<img /);
    expect(html).toContain('alt="Rosa"');
    expect(html).toContain('loading="lazy"');
    expect(html).toContain('decoding="async"');
    expect(html).toContain('width="44"');
    expect(html).toContain('height="44"');
    expect(html).toContain('sizes="44px"');
    expect(html).toContain(`src="${image.thumbSrc}"`);
    expect(html).toContain(`srcSet="${image.thumbSrc} ${image.thumbWidth}w, ${image.src} ${image.width}w"`);
    expect(html).toContain("object-contain");
    expect(html).not.toContain("rounded-[22%]");
    expect(html).not.toContain("<svg");
  });

  it("still draws the SVG gifts, decorative and unchanged", () => {
    const html = renderToStaticMarkup(createElement(GiftArt, { assetKey: "heart-burst", name: "Heart Burst", size: 48 }));
    expect(html).toMatch(/^<svg/);
    expect(html).toContain('aria-hidden="true"');
    expect(html).not.toContain("<img");
  });
});

