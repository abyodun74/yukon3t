import type { GiftTierName } from "@/lib/gifts-data";
import type { GiftEffectMotion } from "@/lib/gift-effect-plan";

// The richer renderers a gift reveal can use on top of the CSS stage (GiftStage), and the one pure rule that
// picks between them. Client-safe, no I/O, unit-tested (gift-3d-assets.test.ts).
//
//   three  Epic and Legendary: a small React Three Fiber scene (gift-scene-3d.tsx) with a self-hosted GLB model.
//   stage  everything else, and the fallback for all of the above: the CSS layers + static art.
//
// Nothing here is loaded up front: GiftStage only asks for a renderer when a reveal is open, and the libraries are
// dynamically imported from there (next/dynamic, ssr: false).

export type GiftModelAsset = {
  /** Same-origin URL under /gifts/models/. */
  src: string;
  /** Where it came from and under what terms. */
  source: string;
  licence: string;
  /** Procedural stand-in until commissioned art exists. */
  placeholder: boolean;
};

/** Size budget per model file (checked by gift-3d-assets.test.ts). */
export const GIFT_MODEL_MAX_BYTES = 300 * 1024;

const generated = (name: string): GiftModelAsset => ({
  src: `/gifts/models/${name}.glb`,
  source: "YuKon3t, generated by scripts/generate-gift-models.mjs",
  licence: "Original work",
  placeholder: true,
});

export const GIFT_MODEL_FILES = {
  heart: generated("heart"),
  diamond: generated("diamond"),
  "gift-box": generated("gift-box"),
  star: generated("star"),
} as const satisfies Record<string, GiftModelAsset>;

export type GiftModelKey = keyof typeof GIFT_MODEL_FILES;

/** The model each Epic / Legendary marketplace gift's item is revealed with (by item slug). */
export const GIFT_MODEL_FOR_ITEM: Readonly<Record<string, GiftModelKey>> = {
  "kindred-spirit": "heart",
  "luxury-red-rose": "heart",
  "keepsake-locket": "heart",
  "birthday-balloons": "gift-box",
  "playful-kitten": "gift-box",
  "sunset-postcard": "gift-box",
  fireworks: "gift-box",
  "supporter-star": "star",
  "level-up": "star",
  "trophy-frame": "star",
  "midnight-crystal-frame": "diamond",
  "gold-orchid": "diamond",
  "aurora-sweep": "diamond",
  "aurora-frame": "diamond",
};

/** The model for a single-item gift, or null (boxes and unmapped items stay on the stage). */
export function resolveGiftModel(items: readonly { slug: string }[]): GiftModelAsset | null {
  if (items.length !== 1) return null;
  const key = GIFT_MODEL_FOR_ITEM[items[0].slug];
  return key ? GIFT_MODEL_FILES[key] : null;
}

export type GiftRenderer = "three" | "stage";

/**
 * Which renderer a reveal uses. Only with full motion (never with reduce motion or on a low-end device); 3D only for Epic / Legendary with a model and WebGL.
 * A gift with a signature motion (gift-signature-motion.ts, e.g. Birthday Balloons' release from the box) always uses
 * the stage: the signature is its reveal, and the 3D model would only cover it.
 */
export function giftRenderer(input: {
  tier: GiftTierName;
  motion: GiftEffectMotion;
  webgl: boolean;
  hasModel: boolean;
  hasSignature: boolean;
}): GiftRenderer {
  if (input.motion !== "full" || input.hasSignature) return "stage";
  if ((input.tier === "EPIC" || input.tier === "LEGENDARY") && input.hasModel && input.webgl) return "three";
  return "stage";
}

/** The canvas's device-pixel-ratio range: never above 2, lower on a device that may struggle. */
export function giftCanvasDpr(devicePixelRatio: number, lowEnd: boolean): [number, number] {
  const ratio = Number.isFinite(devicePixelRatio) && devicePixelRatio > 0 ? devicePixelRatio : 1;
  const max = Math.min(lowEnd ? 1.25 : 2, Math.max(1, ratio));
  return [1, max];
}

/** One WebGL canvas at a time, app-wide: a second reveal (or a replay racing a close) falls back to the stage. */
let canvasHolder: symbol | null = null;
const canvasListeners = new Set<() => void>();

function notifyCanvasListeners() {
  for (const listener of canvasListeners) listener();
}

/** Takes the one canvas slot for `token`; null when someone else holds it. The returned function gives it back. */
export function acquireGiftCanvas(token: symbol = Symbol("gift-canvas")): (() => void) | null {
  if (canvasHolder && canvasHolder !== token) return null;
  canvasHolder = token;
  notifyCanvasListeners();
  return () => {
    if (canvasHolder !== token) return;
    canvasHolder = null;
    notifyCanvasListeners();
  };
}

/** Who holds the canvas slot (for useSyncExternalStore). */
export function giftCanvasHolder(): symbol | null {
  return canvasHolder;
}

export function subscribeGiftCanvas(listener: () => void): () => void {
  canvasListeners.add(listener);
  return () => canvasListeners.delete(listener);
}
